import { mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { afterAll, beforeAll, describe, expect, test } from "vitest";
import { discover } from "../../src/modules/indexing/discover.js";

let root: string;

async function write(rel: string, body = "export const x = 1;\n") {
  const abs = path.join(root, ...rel.split("/"));
  await mkdir(path.dirname(abs), { recursive: true });
  await writeFile(abs, body);
}

beforeAll(async () => {
  root = await mkdtemp(path.join(tmpdir(), "gk-discover-"));
  await write("package.json", "{}");
  await write("tsconfig.json", "{}");
  await write("README.md", "# demo\n");
  await write("src/main.ts");
  await write("src/App.tsx", "export const App = () => <div />;\n");
  await write("src/gen.ts", "// @generated by codegen\nexport type A = string;\n");
  await write("src/types.d.ts", "declare const x: number;\n");
  await write("src/data.js", "x".repeat(600 * 1024));
  await write("public/vendor.min.js", "var a=1;\n");
  await write("node_modules/react/index.js");
  await write("packages/ui/package.json", "{}");
  await write("packages/ui/src/Button.tsx", "export const Button = () => <button />;\n");
});

afterAll(async () => {
  await rm(root, { recursive: true, force: true });
});

describe("discover", () => {
  test("keeps only real source files, sorted", async () => {
    const r = await discover(root);
    expect(r.files.map((f) => f.path)).toEqual([
      "packages/ui/src/Button.tsx",
      "src/App.tsx",
      "src/gen.ts",
      "src/main.ts",
    ]);
    expect(r.files.find((f) => f.path === "src/gen.ts")?.generated).toBe(true);
  });

  test("records skip reasons", async () => {
    const r = await discover(root);
    expect(Object.fromEntries(r.skipped.map((s) => [s.path, s.reason]))).toEqual({
      "public/vendor.min.js": "minified",
      "src/data.js": "too_large",
      "src/types.d.ts": "declaration",
    });
  });

  test("attaches language, package and tsconfig", async () => {
    const r = await discover(root);
    const button = r.files.find((f) => f.path === "packages/ui/src/Button.tsx");
    expect(button).toMatchObject({ lang: "tsx", pkg: "packages/ui", tsconfig: "tsconfig.json" });
    const main = r.files.find((f) => f.path === "src/main.ts");
    expect(main).toMatchObject({ lang: "ts", pkg: "", tsconfig: "tsconfig.json" });
    expect(main?.abs).toBe(path.join(root, "src", "main.ts"));
  });

  test("counts add up and paths are POSIX", async () => {
    const r = await discover(root);
    expect(r.counts.indexed + r.counts.skipped + r.counts.notSource).toBe(r.counts.listed);
    expect(r.counts.notSource).toBe(4);
    expect([...r.files, ...r.skipped].every((f) => !f.path.includes("\\"))).toBe(true);
  });

  test("is deterministic", async () => {
    const [a, b] = await Promise.all([discover(root), discover(root)]);
    expect(a.files).toEqual(b.files);
    expect(a.skipped).toEqual(b.skipped);
  });

  test("indexes the sample-js fixture", async () => {
    const r = await discover(path.resolve("fixtures/sample-js"));
    expect(r.files).toHaveLength(11);
    expect(r.files.every((f) => f.lang === "js")).toBe(true);
  });
});