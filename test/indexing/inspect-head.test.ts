import { mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { afterAll, beforeAll, describe, expect, test } from "vitest";
import { inspectHead, looksMinified } from "../../src/modules/indexing/inspect-head.js";

let dir: string;
const file = (name: string) => path.join(dir, name);
const NORMAL = "export function add(a, b) {\n  return a + b;\n}\n";

beforeAll(async () => {
  dir = await mkdtemp(path.join(tmpdir(), "gk-head-"));
  await writeFile(file("normal.js"), "export function add(a, b) {\n  return a + b;\n}\n");
  await writeFile(file("empty.js"), "");
  await writeFile(file("normal.js"), NORMAL);
  await writeFile(file("big.js"), "x".repeat(600 * 1024));
  await writeFile(file("gen.ts"), "// @generated by codegen\nexport type A = { id: string };\n");
  await writeFile(file("dne.ts"), "/* DO NOT EDIT: produced by protoc */\nexport const x = 1;\n");
  await writeFile(file("min.js"), `var a=1;${"function b(){return a+1};".repeat(200)}\n`);
  await writeFile(file("crlf.js"), "export const a = 1;\r\nexport const b = 2;\r\n");
});

afterAll(async () => {
  await rm(dir, { recursive: true, force: true });
});

describe("inspectHead", () => {
    test("normal source is indexed", async () => {
        expect(await inspectHead(file("normal.js"))).toEqual({
          size: Buffer.byteLength(NORMAL),
          reason: null,
        });
      });

  test("empty file is indexed", async () => {
    expect((await inspectHead(file("empty.js"))).reason).toBeNull();
  });

  test("files over the size limit are too_large", async () => {
    expect((await inspectHead(file("big.js"))).reason).toBe("too_large");
  });

  test("size limit is configurable", async () => {
    expect((await inspectHead(file("normal.js"), { maxBytes: 10 })).reason).toBe("too_large");
  });

  test("generated headers are detected", async () => {
    expect((await inspectHead(file("gen.ts"))).reason).toBe("generated");
    expect((await inspectHead(file("dne.ts"))).reason).toBe("generated");
  });

  test("single long line is minified", async () => {
    expect((await inspectHead(file("min.js"))).reason).toBe("minified");
  });

  test("Windows line endings are not minified", async () => {
    expect((await inspectHead(file("crlf.js"))).reason).toBeNull();
  });
});

describe("looksMinified", () => {
  test("formatted code is not minified", () => {
    expect(looksMinified("const a = 1;\nconst b = 2;\n")).toBe(false);
  });

  test("high average line length is minified", () => {
    expect(looksMinified(`${"a".repeat(400)}\n${"b".repeat(400)}`)).toBe(true);
  });
});